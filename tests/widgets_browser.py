"""Shared control regressions against the actual extension entry editor."""
import json


def run_widget_regressions(page, js, click, labels, key, screenshot):
    click('newEntryButton')
    js("globalThis.widgetRow=s.querySelector('.values-table tbody tr');globalThis.typeSelect=widgetRow.querySelector('[data-value-type]');globalThis.typeTrigger=typeSelect.parentElement.querySelector('.qf-combo-trigger');typeSelect.querySelector('[value=bool]').disabled=true;globalThis.typeEvents=[];typeSelect.addEventListener('input',()=>typeEvents.push('input'));typeSelect.addEventListener('change',()=>typeEvents.push('change'))")
    assert js("typeTrigger.getAttribute('role')==='combobox' && typeSelect.tabIndex===-1")
    js('typeTrigger.click()')
    assert js("s.activeElement===typeTrigger && !!s.querySelector('.qf-select-popup')")
    assert js("s.querySelector('.qf-select-option[aria-disabled=true]').textContent") == labels['type_bool']
    key('ArrowDown')
    key('Enter')
    assert js("typeSelect.value==='number' && typeEvents.join(',')==='input,change' && !s.querySelector('.qf-select-popup')")
    assert js("typeTrigger.querySelector('.qf-combo-label').textContent") == labels['type_number']
    js('typeTrigger.click()')
    key('ArrowDown')
    key('Escape')
    assert js("typeSelect.value==='number' && !s.querySelector('.qf-select-popup') && s.activeElement===typeTrigger && document.querySelector('quickfill-sidebar').style.display!=='none'")
    js("typeSelect.querySelector('[value=bool]').disabled=false;typeTrigger.click()")
    screenshot('styled-combobox')
    js("Array.from(s.querySelectorAll('.qf-select-option')).find(n=>n.textContent===" + json.dumps(labels['type_date']) + ").click()")
    assert js("typeSelect.value==='date' && !!widgetRow.querySelector('.qf-date-trigger')")
    js("globalThis.dateInput=widgetRow.querySelector('[data-value-input]');dateInput.value='2024-02-29';dateInput.dispatchEvent(new Event('input',{bubbles:true}));widgetRow.querySelector('.qf-date-trigger').click()")
    assert js("s.querySelector('.qf-calendar-day[aria-selected=true]').dataset.date==='2024-02-29'")
    assert js("(()=>{const r=s.querySelector('.qf-calendar').getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()")
    js("s.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true,composed:true,cancelable:true}))")
    assert js("s.activeElement.dataset.date==='2024-03-01'")
    js("s.activeElement.click()")
    assert js("dateInput.value==='2024-03-01' && !s.querySelector('.qf-calendar')")
    js("widgetRow.querySelector('.qf-date-trigger').click();s.querySelector('.qf-calendar-heading button:last-child').click()")
    assert js("!!s.querySelector('.qf-calendar-day[data-date=\"2024-04-15\"]')")
    screenshot('styled-calendar')
    key('Escape')
    assert js("!s.querySelector('.qf-calendar') && dateInput.value==='2024-03-01' && !!s.querySelector('.entry-editor')")
    js("typeSelect.value='datetime';typeSelect.dispatchEvent(new Event('change'));globalThis.dateTimeInput=widgetRow.querySelector('[data-value-input]');dateTimeInput.value='2025-12-31T23:45';dateTimeInput.dispatchEvent(new Event('input',{bubbles:true}));widgetRow.querySelector('.qf-date-trigger').click();s.querySelector('.qf-calendar-day[data-date=\"2026-01-01\"]').click();s.querySelector('.qf-calendar-time input').value='8';s.querySelectorAll('.qf-calendar-time input')[1].value='9'")
    screenshot('styled-datetime')
    js("s.querySelector('.qf-calendar-actions .primary').click()")
    assert js("dateTimeInput.value==='2026-01-01T08:09' && !s.querySelector('.qf-calendar')")
    js("widgetRow.querySelector('.qf-date-trigger').click();s.querySelector('.qf-calendar-time input').value='25';s.querySelector('.qf-calendar-actions .primary').click()")
    assert js("!!s.querySelector('.qf-calendar') && dateTimeInput.value==='2026-01-01T08:09' && s.activeElement===s.querySelector('.qf-calendar-time input')")
    key('Escape')
    js("dateTimeInput.value='2026-01-01T08:09:37.250';dateTimeInput.dispatchEvent(new Event('input',{bubbles:true}));widgetRow.querySelector('.qf-date-trigger').click();s.querySelector('.qf-calendar-actions .primary').click()")
    assert js("dateTimeInput.value==='2026-01-01T08:09:37.250'")
    click('cancel')
    print('PASS: themed combobox keyboard/disabled/events/Escape, calendar leap-day/month navigation/viewport, datetime commit and invalid time')
